describe("Property 1: Filter-matching", () => {
  /**
   * **Validates: Requirements 1.1, 1.3, 2.2, 3.2, 4.2, 4.3**
   *
   * For any combination of active filters and any corpus state, every site
   * returned by the Surf Engine satisfies all active filter constraints.
   */
  it("returned site satisfies all active filter constraints", async () => {
    await fc.assert(
      fc.asyncProperty(corpusArb, surfParamsArb, async (corpus, params) => {
        const db = createMockD1(corpus);
        const result = await surf(db, params);

        if (result.status === "ok") {
          const site = result.site;

          // NSFW must be excluded
          expect(site.nsfw).toBe(0);

          // Mood filter check
          if (params.mood && params.mood !== "surprise") {
            const tags = site.mood_tags.split(";");
            expect(tags).toContain(params.mood);
          }

          // Character filter check
          if (params.character) {
            expect(site.character).toBe(params.character);
          }

          // Stack filter check (OR within dimension)
          if (params.stacks && params.stacks.length > 0) {
            expect(params.stacks).toContain(site.stack);
          }

          // Host filter check (OR within dimension)
          if (params.hosts && params.hosts.length > 0) {
            expect(params.hosts).toContain(site.host);
          }

          // Static or dynamic filter check
          if (params.staticOrDynamic) {
            expect(site.static_or_dynamic).toBe(params.staticOrDynamic);
          }

          // Seen-list check
          if (params.seen && params.seen.length > 0) {
            const validSeen = params.seen.filter(
              (id) => Number.isInteger(id) && id > 0
            );
            expect(validSeen).not.toContain(site.id);
          }
        }
      }),
      { numRuns: 100 }
    );
  });
});

