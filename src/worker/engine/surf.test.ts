// Property 5: Surprise equivalence
// Feature: mvp-stumble, Property 5: Surprise and absent mood are equivalent
// ---------------------------------------------------------------------------

describe("Property 5: Surprise equivalence", () => {
  /**
   * **Validates: Requirements 2.3, 2.4**
   *
   * The candidate pool when mood=surprise is identical to the candidate pool
   * when mood is omitted entirely.
   */
  it("mood=surprise produces same pool as mood absent", async () => {
    await fc.assert(
      fc.asyncProperty(corpusArb, surfParamsArb, async (corpus, baseParams) => {
        // Compute pools using the ground-truth helper
        const paramsWithSurprise: SurfParams = {
          ...baseParams,
          mood: "surprise",
        };
        const paramsWithoutMood: SurfParams = {
          ...baseParams,
          mood: undefined,
        };

        const poolSurprise = computeMatchingPool(corpus, paramsWithSurprise);
        const poolNoMood = computeMatchingPool(corpus, paramsWithoutMood);

        // Both pools must contain the same sites
        const idsSurprise = poolSurprise.map((s) => s.id).sort();
        const idsNoMood = poolNoMood.map((s) => s.id).sort();
        expect(idsSurprise).toEqual(idsNoMood);

        // Also verify via the engine: if surprise returns a site, it should
        // be in the no-mood pool
        const db = createMockD1(corpus);
        const result = await surf(db, paramsWithSurprise);
        if (result.status === "ok") {
          const noMoodIds = poolNoMood.map((s) => s.id);
          expect(noMoodIds).toContain(result.site.id);
        }
      }),
      { numRuns: 100 }
    );
  });
});

