describe("Property 3: Seen-list exclusion", () => {
  /**
   * **Validates: Requirements 10.5**
   *
   * For any surf request containing a seen-list of site IDs, the Surf
   * Engine never returns a site whose ID appears in the seen-list.
   */
  it("returned site ID never appears in seen-list", async () => {
    const seenParamsArb = fc.record({
      mood: fc.constant(undefined),
      character: fc.constant(undefined),
      stacks: fc.constant(undefined),
      hosts: fc.constant(undefined),
      staticOrDynamic: fc.constant(undefined),
      seen: fc.constant(undefined), // placeholder, set dynamically
    });

    await fc.assert(
      fc.asyncProperty(corpusArb, fc.integer({ min: 1, max: 4 }), async (corpus, seenCount) => {
        // Pick a subset of IDs as the seen-list (not all, so some remain)
        const nonNsfw = corpus.filter((s) => s.nsfw === 0);
        if (nonNsfw.length <= 1) return; // Skip trivial corpora

        const actualSeenCount = Math.min(seenCount, nonNsfw.length - 1);
        const seen = nonNsfw.slice(0, actualSeenCount).map((s) => s.id);

        const params: SurfParams = { seen };
        const db = createMockD1(corpus);
        const result = await surf(db, params);

        if (result.status === "ok") {
          expect(seen).not.toContain(result.site.id);
        }
      }),
      { numRuns: 100 }
    );
  });

  it("seen-list with all matching IDs returns exhausted", async () => {
    await fc.assert(
      fc.asyncProperty(corpusArb, async (corpus) => {
        // Seen all non-NSFW sites
        const nonNsfw = corpus.filter((s) => s.nsfw === 0);
        if (nonNsfw.length === 0) return; // Skip if all NSFW

        const seen = nonNsfw.map((s) => s.id);
        const params: SurfParams = { seen };
        const db = createMockD1(corpus);
        const result = await surf(db, params);

        expect(result.status).toBe("exhausted");
      }),
      { numRuns: 100 }
    );
  });
});

