describe("Property 6: Build filter OR-within-AND-across dimensions", () => {
  /**
   * **Validates: Requirements 4.2, 4.3**
   *
   * Multi-value within the same dimension uses OR; across dimensions uses AND.
   */
  it("multi-value within dimension uses OR, across dimensions uses AND", async () => {
    await fc.assert(
      fc.asyncProperty(
        corpusArb,
        fc.uniqueArray(fc.constantFrom(...validStacks), { minLength: 1, maxLength: 3 }),
        fc.uniqueArray(fc.constantFrom(...validHosts), { minLength: 1, maxLength: 3 }),
        async (corpus, stacks, hosts) => {
          const params: SurfParams = { stacks, hosts };
          const db = createMockD1(corpus);
          const result = await surf(db, params);

          if (result.status === "ok") {
            const site = result.site;

            // OR within stacks: site.stack must be one of the selected stacks
            expect(stacks).toContain(site.stack);

            // OR within hosts: site.host must be one of the selected hosts
            expect(hosts).toContain(site.host);
          }
        }
      ),
      { numRuns: 100 }
    );
  });

  it("single dimension filter with multiple values uses OR", async () => {
    await fc.assert(
      fc.asyncProperty(
        corpusArb,
        fc.uniqueArray(fc.constantFrom(...validStacks), { minLength: 2, maxLength: 4 }),
        async (corpus, stacks) => {
          const params: SurfParams = { stacks };
          const db = createMockD1(corpus);
          const result = await surf(db, params);

          if (result.status === "ok") {
            // The returned site's stack must be one of the selected values
            expect(stacks).toContain(result.site.stack);
          }
        }
      ),
      { numRuns: 100 }
    );
  });

  it("AND across dimensions: mood + character + build all satisfied", async () => {
    await fc.assert(
      fc.asyncProperty(
        corpusArb,
        fc.constantFrom(...validMoods),
        fc.constantFrom(...validCharacters),
        fc.uniqueArray(fc.constantFrom(...validStacks), { minLength: 1, maxLength: 2 }),
        async (corpus, mood, character, stacks) => {
          const params: SurfParams = { mood, character, stacks };
          const db = createMockD1(corpus);
          const result = await surf(db, params);

          if (result.status === "ok") {
            const site = result.site;
            const tags = site.mood_tags.split(";");
            expect(tags).toContain(mood);
            expect(site.character).toBe(character);
            expect(stacks).toContain(site.stack);
          }
        }
      ),
      { numRuns: 100 }
    );
  });
});

